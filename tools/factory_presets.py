"""Build the editable factory bank from human knob settings. No device access.

Writes normal FPST v1 records; compiler input/header generation only, no audio
render, DSP-load check or listening test. IR references are always built-in.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import zlib

ROOT=Path(__file__).resolve().parents[1]

def build_bank(output, header=None):
    source=json.loads((ROOT/'presets/factory.json').read_text(encoding='utf-8'))
    catalog=json.loads((ROOT/'web/effects.json').read_text(encoding='utf-8'))['effects']
    rows=source['presets'];records=[];manifest=[]
    if len(rows)!=20:raise ValueError('factory bank requires exactly 20 presets')
    for number,row in enumerate(rows,1):
        name=row['name'].encode('ascii');chain=row['chain']
        if row['number']!=number or not 1<=len(name)<=16 or not 1<=len(chain)<=6:raise ValueError('invalid factory preset identity/chain')
        record=bytearray(264);record[:3]=b'FP\x01';record[4:4+len(name)]=name
        record[20]=next((i for i,b in enumerate(chain) if 45<=b['type']<=51),0)
        record[21:27]=bytes(range(6));settings=[]
        for slot in range(6):
            offset=32+36*slot
            if slot>=len(chain):record[offset]=255;continue
            block=chain[slot];type_id=block['type'];meta=catalog[str(type_id)];params=meta['params']
            if type_id==33:raise ValueError('factory presets cannot require capture files')
            values={p['name']:p['initial'] for p in params}
            if set(block['params'])-set(values):raise ValueError('unknown knob in '+row['name'])
            values.update(block['params'])
            if type_id in (19,20) and values['E.LEVEL' if type_id==19 else 'MIX']>25:raise ValueError('reverb level exceeds 25')
            record[offset:offset+4]=bytes([type_id,1,0,len(params)])
            for i,p in enumerate(params):
                value=values[p['name']]
                if not isinstance(value,int) or not p['min']<=value<=p['max']:raise ValueError('invalid knob '+p['name'])
                # Appended models store human units / scale. IR VOL maps 0..100 to 0..2.
                if type_id==3:dsp=value/50.0
                elif type_id>=9:dsp=value/p['scale']
                else:raise ValueError('factory bank uses unsupported legacy mapping')
                struct.pack_into('<f',record,offset+4+4*i,dsp)
            settings.append(dict(type=type_id,effect=meta['short'],params=values))
        record[248:252]=b'\xff'*4
        struct.pack_into('<I',record,260,zlib.crc32(record[:260]))
        records.append(bytes(record));manifest.append(dict(number=number,name=row['name'],description=row['description'],chain=settings,sha256=hashlib.sha256(record).hexdigest()))
    output=Path(output);output.mkdir(parents=True,exist_ok=True)
    for row,record in zip(rows,records):(output/('%02d.fpst'%row['number'])).write_bytes(record)
    (output/'manifest.json').write_text(json.dumps(dict(format='frost-factory-presets',version=source['version'],reverb_mix_limit=25,presets=manifest),indent=2)+'\n',encoding='utf-8')
    if header:
        text=['/* Generated by tools/factory_presets.py from presets/factory.json. */','#ifndef FROST_FACTORY_BANK_H','#define FROST_FACTORY_BANK_H','#define FROST_FACTORY_COUNT 20u','static const uint8_t frost_factory_records[FROST_FACTORY_COUNT][264]={']
        for record in records:
            text.append(' {')
            for o in range(0,264,24):text.append('  '+','.join('0x%02x'%v for v in record[o:o+24])+',')
            text.append(' },')
        text.extend(['};','#endif','']);Path(header).write_text('\n'.join(text),encoding='utf-8')
    return manifest

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=ROOT/'build/factory-presets')
    parser.add_argument('--header',type=Path,default=ROOT/'firmware/controller/factory_bank.h')
    args=parser.parse_args();rows=build_bank(args.output,args.header)
    print('Built',len(rows),'editable preset records; no tests, device access or audio rendering.')
